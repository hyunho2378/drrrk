export function applySync(root) {
  Object.keys(SYNC).forEach((id) => {
    const p = root.querySelector('p[data-node="' + id + '"]');
    if (!p || p.dataset.sync) return;
    p.dataset.sync = '1';
    setText(p, SYNC[id]);
    Object.assign(p.style, { width: 'auto', whiteSpace: 'pre' });
  });
}
